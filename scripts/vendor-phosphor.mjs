#!/usr/bin/env node
// Vendors the Phosphor icons (MIT) the app uses into src/content/icons.js.
//
// Only the icons listed in ICONS below are copied, as inline SVG markup, so pages carry a few
// hundred bytes per icon and no icon font or sprite request. Weight: "regular".
// To add an icon: pick it on https://phosphoricons.com/, add its name here, rerun, then use
// the camelCase export: svgIcon(pianoKeys) in templates (svgIcon from src/core/icon.js),
// el("button", { icon: icons.pianoKeys, ... }) in pages.
//
// Usage: node scripts/vendor-phosphor.mjs [version]   (default: the version in VERSION.json)
// Needs: npm and network access to the npm registry. Writes:
//   src/content/icons.js, src/vendor/phosphor/LICENSE, src/vendor/phosphor/VERSION.json
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ICONS = [
	"arrow-counter-clockwise",
	"arrow-left",
	"arrow-right",
	"arrows-clockwise",
	"book-open",
	"code",
	"cloud-arrow-down",
	"copy",
	"download-simple",
	"ear",
	"gear",
	"github-logo",
	"hand-palm",
	"house",
	"key",
	"lightbulb",
	"link",
	"link-break",
	"microphone",
	"music-note",
	"music-notes",
	"notebook",
	"pause",
	"piano-keys",
	"play",
	"plugs",
	"printer",
	"question",
	"shuffle",
	"speaker-high",
	"stop",
	"text-aa",
	"translate",
	"trash",
	"upload-simple",
];

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendorDir = join(root, "src/vendor/phosphor");
const versionFile = join(vendorDir, "VERSION.json");
const current = existsSync(versionFile) ? JSON.parse(readFileSync(versionFile, "utf8")) : {};
const version = process.argv[2] || current.version || "2.1.1";
if (!/^\d+\.\d+\.\d+$/.test(version)) {
	console.error("usage: vendor-phosphor.mjs <exact version, e.g. 2.1.1>");
	process.exit(1);
}

const camel = (name) => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const work = mkdtempSync(join(tmpdir(), "phosphor-vendor-"));
try {
	// npm pack verifies the registry integrity hash; --ignore-scripts keeps it inert.
	const tgz = execFileSync("npm", ["pack", `@phosphor-icons/core@${version}`, "--ignore-scripts", "--silent"], { cwd: work, encoding: "utf8" }).trim();
	const tgzSha = createHash("sha256").update(readFileSync(join(work, tgz))).digest("hex");
	execFileSync("tar", ["-xzf", tgz], { cwd: work });
	const pkg = join(work, "package");
	const meta = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8"));
	const lines = [];
	for (const name of ICONS) {
		const svg = readFileSync(join(pkg, "assets/regular", `${name}.svg`), "utf8").trim();
		const m = /^<svg[^>]*viewBox="0 0 256 256"[^>]*>([\s\S]*)<\/svg>$/.exec(svg);
		if (!m) throw new Error(`${name}: unexpected SVG shape`);
		const inner = m[1].trim();
		if (/[`$\\]|<(script|style|foreignObject)/i.test(inner)) throw new Error(`${name}: unexpected content`);
		lines.push(`export const ${camel(name)} = \`${inner}\`;`);
	}
	mkdirSync(vendorDir, { recursive: true });
	copyFileSync(join(pkg, "LICENSE"), join(vendorDir, "LICENSE"));
	writeFileSync(versionFile, `${JSON.stringify({ name: "@phosphor-icons/core", version, license: meta.license, weight: "regular", tarballSha256: tgzSha, icons: ICONS }, null, 2)}\n`);
	const out = `// Generated by scripts/vendor-phosphor.mjs from @phosphor-icons/core ${version} (MIT, see
// src/vendor/phosphor/LICENSE). Do not edit by hand: add the icon name in the script and rerun.
// Each export is the inner markup of a 256x256 icon; svgIcon() in src/core/icon.js wraps it.
// Icons are decorative: they always sit next to visible text, so they are hidden from
// assistive technology and never carry meaning alone.

${lines.join("\n")}
`;
	writeFileSync(join(root, "src/content/icons.js"), out);
	console.log(`vendored ${ICONS.length} Phosphor icons from ${version} (tarball sha256=${tgzSha})`);
} finally {
	rmSync(work, { recursive: true, force: true });
}
